static void Expect(bool condition, const char *message)
{
    if (condition)
    {
        return;
    }
    LaiueTestRuntimeWrite("certificate validation test failed: ");
    LaiueTestRuntimeWrite(message);
    LaiueTestRuntimeWrite("\r\n");
    LaiueTestRuntimeExit(1);
}

static NetworkEndpoint Parse(const char *text)
{
    NetworkEndpoint endpoint;
    Expect(NetworkEndpointParse(
               text, LAIUE_NETWORK_DEFAULT_PORT, &endpoint) ==
               NETWORK_ENDPOINT_PARSE_OK,
           "fixture endpoint");
    return endpoint;
}

static bool ValidFor(const char *endpointText)
{
    NetworkEndpoint endpoint = Parse(endpointText);
    return NetworkCertificateValidateLeafIdentity(
        &endpoint, certificateDer, sizeof(certificateDer));
}

static bool ReplaceBytes(
    uint8_t *bytes, uint32_t size,
    const char *needle, const char *replacement)
{
    uint32_t length = 0;
    while (needle[length] != '\0' &&
           replacement[length] != '\0')
    {
        ++length;
    }
    if (needle[length] != '\0' ||
        replacement[length] != '\0' || length == 0)
    {
        return false;
    }
    for (uint32_t offset = 0;
         offset + length <= size; ++offset)
    {
        uint32_t index = 0;
        while (index < length &&
               bytes[offset + index] ==
                   (uint8_t)needle[index])
        {
            ++index;
        }
        if (index != length)
        {
            continue;
        }
        for (index = 0; index < length; ++index)
        {
            bytes[offset + index] =
                (uint8_t)replacement[index];
        }
        return true;
    }
    return false;
}

LAIUE_TEST_ENTRY(CertificateValidationTestEntryPoint)
{
    Expect(ValidFor("game.example.test"), "exact DNS SAN");
    Expect(ValidFor("GAME.EXAMPLE.TEST"), "DNS case folding");
    Expect(ValidFor("192.0.2.10"), "IPv4 SAN");
    Expect(ValidFor("2001:db8::10"), "IPv6 SAN");

    Expect(!ValidFor("ignored.example.test"), "CN fallback forbidden");
    Expect(!ValidFor("other.example.test"), "wrong DNS SAN");
    Expect(!ValidFor("192.0.2.11"), "wrong IPv4 SAN");
    Expect(!ValidFor("2001:db8::11"), "wrong IPv6 SAN");

    NetworkEndpoint endpoint = Parse("game.example.test");
    Expect(!NetworkCertificateValidateLeafIdentity(
               &endpoint, certificateDer,
               (uint32_t)sizeof(certificateDer) - 1U),
           "truncated DER");
    Expect(!NetworkCertificateValidateLeafIdentity(
               &endpoint, NULL, 0U),
           "empty DER");

    uint8_t expired[sizeof(certificateDer)];
    for (uint32_t index = 0;
         index < sizeof(certificateDer); ++index)
    {
        expired[index] = certificateDer[index];
    }
    Expect(ReplaceBytes(
               expired, sizeof(expired),
               "21260701213450Z", "20250701213450Z"),
           "expired fixture date");
    Expect(!NetworkCertificateValidateLeafIdentity(
               &endpoint, expired, sizeof(expired)),
           "expired certificate");

    LAIUE_TEST_SUCCESS();
}
