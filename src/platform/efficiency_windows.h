#pragma once

#include <stdbool.h>

/* Как процесс расходует энергию Windows. */
typedef enum PlatformPowerMode
{
    /* QoS выбирает система, класс приоритета прежний. */
    PLATFORM_POWER_DEFAULT,
    /* Режим эффективности, как у переключателя в диспетчере задач: EcoQoS
     * (Windows 11 держит потоки на энергоэффективных ядрах и сниженной
     * частоте) и низкий базовый приоритет; у процесса зелёный лист. */
    PLATFORM_POWER_EFFICIENCY,
    /* Высокий QoS: система не замедляет процесс, даже когда его окно
     * свёрнуто или закрыто другими. Класс приоритета прежний. */
    PLATFORM_POWER_PERFORMANCE,
} PlatformPowerMode;

/* Выход из режима эффективности возвращает класс приоритета, который был до
 * входа; процесс, уже работавший с низким приоритетом, таким и остаётся.
 * Повторная установка того же режима ничего не меняет. false — система не
 * приняла QoS (Windows старше 10 1709); приоритет при этом всё равно
 * меняется. */
bool PlatformPowerModeSet(PlatformPowerMode mode);

/* Поток, которому нельзя замедляться в режиме эффективности (вывод звука),
 * явно просит высокий QoS: EcoQoS процесса его тогда не касается. */
bool PlatformEfficiencyExemptCurrentThread(void);
