#pragma once

#include <stdbool.h>

/* Режим эффективности, как у переключателя в диспетчере задач Windows:
 * процесс получает EcoQoS (Windows 11 держит его потоки на энергоэффективных
 * ядрах и сниженной частоте) и низкий базовый приоритет, а диспетчер задач
 * показывает у него зелёный лист. Выход возвращает класс приоритета, который
 * был до входа, и снова отдаёт QoS на усмотрение системы. Повторный вход или
 * выход ничего не меняет. false — система не приняла EcoQoS (Windows старше
 * 10 1709); приоритет при этом всё равно меняется. */
bool PlatformEfficiencyModeSet(bool enabled);

/* Поток, которому нельзя замедляться в режиме эффективности (вывод звука),
 * явно просит высокий QoS: EcoQoS процесса его тогда не касается. */
bool PlatformEfficiencyExemptCurrentThread(void);
