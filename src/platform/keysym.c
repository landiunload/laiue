/* Legacy Cyrillic keysyms 0x6a1-0x6ff, as X11's keysymdef.h maps them.
 * 0x6c0-0x6df hold the small letters in KOI8-R order, 0x6e0-0x6ff the
 * capitals in the same order. */
static const uint16_t cyrillic[0x6FFu - 0x6A1u + 1u] = {
    /* 0x6a1 */ 0x0452, 0x0453, 0x0451, 0x0454, 0x0455, 0x0456, 0x0457,
    /* 0x6a8 */ 0x0458, 0x0459, 0x045A, 0x045B, 0x045C, 0x0491, 0x045E, 0x045F,
    /* 0x6b0 */ 0x2116, 0x0402, 0x0403, 0x0401, 0x0404, 0x0405, 0x0406, 0x0407,
    /* 0x6b8 */ 0x0408, 0x0409, 0x040A, 0x040B, 0x040C, 0x0490, 0x040E, 0x040F,
    /* 0x6c0 */ 0x044E, 0x0430, 0x0431, 0x0446, 0x0434, 0x0435, 0x0444, 0x0433,
    /* 0x6c8 */ 0x0445, 0x0438, 0x0439, 0x043A, 0x043B, 0x043C, 0x043D, 0x043E,
    /* 0x6d0 */ 0x043F, 0x044F, 0x0440, 0x0441, 0x0442, 0x0443, 0x0436, 0x0432,
    /* 0x6d8 */ 0x044C, 0x044B, 0x0437, 0x0448, 0x044D, 0x0449, 0x0447, 0x044A,
    /* 0x6e0 */ 0x042E, 0x0410, 0x0411, 0x0426, 0x0414, 0x0415, 0x0424, 0x0413,
    /* 0x6e8 */ 0x0425, 0x0418, 0x0419, 0x041A, 0x041B, 0x041C, 0x041D, 0x041E,
    /* 0x6f0 */ 0x041F, 0x042F, 0x0420, 0x0421, 0x0422, 0x0423, 0x0416, 0x0412,
    /* 0x6f8 */ 0x042C, 0x042B, 0x0417, 0x0428, 0x042D, 0x0429, 0x0427, 0x042A,
};

uint32_t LaiueKeysymToCodepoint(uint32_t keysym)
{
    /* Latin-1 keysyms are their own code points. */
    if ((keysym >= 0x20u && keysym <= 0x7Eu) || (keysym >= 0xA0u && keysym <= 0xFFu))
        return keysym;
    /* 0x01000000 plus the code point: any character a layout names directly. */
    if (keysym >= 0x01000100u && keysym <= 0x0110FFFFu)
    {
        const uint32_t codepoint = keysym - 0x01000000u;
        return codepoint >= 0xD800u && codepoint <= 0xDFFFu ? 0u : codepoint;
    }
    if (keysym >= 0x6A1u && keysym <= 0x6FFu)
        return cyrillic[keysym - 0x6A1u];
    /* The currency keysyms, EuroSign among them, are their own code points. */
    if (keysym >= 0x20A0u && keysym <= 0x20ACu)
        return keysym;
    /* The keypad with Num Lock: KP_Space, then '*' to '9', and '='. */
    if (keysym == 0xFF80u)
        return 0x20u;
    if ((keysym >= 0xFFAAu && keysym <= 0xFFB9u) || keysym == 0xFFBDu)
        return keysym - 0xFF80u;
    return 0u;
}
