// JPEG (ITU-T T.81) в RGBA8. Поддержаны и последовательный режим
// (SOF0, SOF1), и прогрессивный (SOF2) с кодированием Хаффмана: это то,
// что выдают все обычные редакторы и камеры. Арифметическое
// кодирование, потери без DCT (SOF3) и иерархический режим отвергаются
// явным сообщением, а не разбираются наполовину.
//
// Альфы у JPEG нет: hasAlpha всегда false, а альфа-канал заполняется
// непрозрачным. Кадр всегда один.
//
// Цветность, записанная вдвое реже (4:2:0 и 4:2:2), восстанавливается
// треугольным фильтром: отсчёт лежит посередине своей пары, и вклад
// ближнего соседа втрое больше дальнего. Повторение ближайшего было бы
// проще, но расходилось бы с любым другим декодером на десятки единиц
// по краям цвета — это измерено на двух сотнях кадров. Более редкие
// отношения вроде 4:1:1 повторяют ближайший отсчёт.
//
// Память выделяет вызывающая сторона: JpegInspect сообщает размер
// картинки и объём рабочего буфера, JpegDecode пишет в оба. Рабочий
// буфер обязан быть выровнен под указатель.

ImageStatus JpegInspect(const void *bytes, uint32_t sizeBytes, ImageInfo *outInfo);

ImageStatus JpegDecode(const void *bytes, uint32_t sizeBytes, const ImageInfo *info, void *pixels,
                       uint32_t pixelBytes, void *scratch, uint32_t scratchBytes);
